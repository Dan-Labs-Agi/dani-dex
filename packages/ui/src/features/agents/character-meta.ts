export function characterLabel(index: number): string {
  const spec = CHARACTER_SPECS[index];
  if (!spec) return "Character";
  const face = CHARACTER_FACES[spec[3]];
  const color = CHARACTER_COLORS[spec[0]];
  const head = (CHARACTER_HEADS[spec[1]] ?? "").toLowerCase();
  const eyes = (CHARACTER_EYES[spec[2]] ?? "").toLowerCase();
  return `${color} ${head}, ${eyes}${face ? `, ${face.toLowerCase()}` : ""}`;
}
